public class Operaciones {
    public void sumar(int op1, int op2) {
        int suma = op1 + op2;
        System.out.println("Suma: " + suma);
    }
    public void restar(int op1, int op2){
        int resta = op1-op2;
        System.out.println("Resta: "+resta);
    }
    public void multiplicar(int op1, int op2){
        int multiplica = op1*op2;
        System.out.println("Multiplicación: "+multiplica);
    }
    public void dividir(int op1, int op2){
        int divide = op1-op2;
        System.out.println("División: "+divide);
    }
}
